# ---- 二、模組 ------------------------------------------------------------
# 兩者用途不同：MODULE_DIRS 決定「哪些資料夾算模組」，MODULE_NAMES 決定「封面印什麼」。
# 故 MODULE_DIRS 通常較長——模組資料夾已存在，但其正式名稱未必已向客戶確認。

# 模組之**正式名稱**。⛔ 未經確認者不得自行填入——封面名稱錯誤即交付瑕疵；
# 未列於此者，封面只印作業名、不印模組名。
MODULE_NAMES = {
    "dp": "平台管理模組",
    "dm": "文件管理模組",
    "et": "教育訓練文件管理模組",
}

# 全部模組資料夾。手冊與測試項目之檔案落在其下，據以判定所屬模組。
MODULE_DIRS = ("dm", "dp", "et")

# ---- 三、命名慣例 --------------------------------------------------------
# 交付文件之檔名格式。模組資料夾下不符此式者視為他人自行撰寫、非本流程產出，
# 四支工具一律略過。⚠️ 新專案之作業編碼未必為「兩碼英文＋兩位數字」。

MANUAL_NAME_RE = re.compile(r"^[A-Z]{2}\d{2}-.+$")        # 如 ET02-課程建立與編輯
OPERATION_CODE_RE = re.compile(r"^(?P<code>[A-Z]{2}\d{2})-(?P<name>.+)$")

# ---- 四、禁用字樣 --------------------------------------------------------
# 屬內部識別，使用者在畫面上看不到、也報不出來，⛔ 不得出現於交付文件。

# 訊息代碼與錯誤代碼。兩者性質相同（內部識別，使用者只看得到文字），修法也相同
# ——改引使用者在畫面上看到的訊息原文，故共用同一條 regex 與同一則錯誤提示。
#
# 第三式為 EDMS 之錯誤代碼（`docs/ref/error-codes.md`，現有 163 種）。它**不會**被
# 下方 TABLE_NAME_RE 攔到：該式的 `[A-Z_]{3,}` 不含數字，故 DP_MAIL_009 之類會整段
# 落空。兩式已實測互斥——表名（ET_ENROLLMENT / ET_QUIZ_ATTEMPT_M）只中 TABLE_NAME_RE，
# 錯誤碼只中本式。
MSG_CODE_RE = re.compile(
    r"[A-Z]{2}-MSG-[A-Z]{2}\d{2}-\d{3}"         # 如 ET-MSG-ET03-003
    r"|\b[A-Z]{2}\d{2}-\d{3}\b"                 # 如 ET03-003
    r"|\b[A-Z]{2}_[A-Z]+(?:_[A-Z]+)*_\d{3}\b"   # 如 ET_COURSE_009、DP_MAIL_009
)

# 資料表名稱，如 BS_INVENTORY。自 MODULE_DIRS 組成，新增模組時毋須另改此處。
TABLE_NAME_RE = re.compile(
    rf"\b({'|'.join(d.upper() for d in MODULE_DIRS)})_[A-Z_]{{3,}}\b")

